"""Operator-only synthetic workflow in an isolated Cloud SQL schema/private GCS.

Requires the supervised local engine gate. Never listens on HTTP or creates real
Firebase identities. No public tables or existing bucket objects are modified.
"""
import json
import os
import re
import subprocess
from urllib.parse import unquote, urlsplit
from uuid import uuid4
from unittest.mock import patch


def main():
    if any(os.getenv(k) for k in ('K_SERVICE', 'CLOUD_RUN_JOB', 'WZOS_DATABASE_URL', 'WZOS_FILES_BUCKET')):
        raise RuntimeError('Operator-only persistence check')
    import psycopg
    from psycopg import sql
    from psycopg.conninfo import make_conninfo
    from services.workspace_preview.postgres import PostgreSQLStorage
    from services.workspace_preview.files import GoogleFiles
    from check_security_workflow import run, SCANNER
    raw = subprocess.check_output(['gcloud', 'secrets', 'versions', 'access', 'latest',
        '--secret=wzos-v2-staging-database-url', '--project=enterprise-gemma2'], text=True).strip()
    parsed = urlsplit(raw)
    base = make_conninfo(host='127.0.0.1', port=5544, dbname='wzos',
        user=unquote(parsed.username), password=unquote(parsed.password), connect_timeout=10)
    schema = 'wzos_release_test_' + uuid4().hex
    assert re.fullmatch(r'wzos_release_test_[a-f0-9]{32}', schema)
    files = GoogleFiles('enterprise-gemma2-wzos-v2-files-staging')
    keys = set()
    original_put = files.put
    def tracked_put(key, *args):
        # All keys are generated by the fresh fixture organizations/files.
        if files.bucket.blob(key).exists(timeout=20):
            raise RuntimeError('Refuse to overwrite a pre-existing object')
        keys.add(key)
        return original_put(key, *args)
    files.put = tracked_put
    storage = None
    with psycopg.connect(base, autocommit=True) as operator:
        operator.execute(sql.SQL('CREATE SCHEMA {}').format(sql.Identifier(schema)))
        try:
            storage = PostgreSQLStorage(make_conninfo(base, options='-csearch_path='+schema))
            storage.initialize()
            with patch.dict(os.environ, {'WZOS_ACCOUNT_WORKSPACE': '1', 'WZOS_FILE_SCAN_REQUIRED': '1',
                    'WZOS_SCANNER_URL': SCANNER, 'WZOS_SMS_MODE': 'disabled', 'WZOS_DAILY_ENABLED': '0',
                    'WZOS_ATLAS_VLLM_ENABLED': '0'}), \
                    patch('services.workspace_preview.storage.SQLiteStorage', return_value=storage), \
                    patch('services.workspace_preview.files.LocalFiles', return_value=files):
                result = run('engine')
            assert result['passed'] == 29
            with storage.connect() as db:
                assert db.execute('SELECT COUNT(*) FROM security_actions').fetchone()[0] >= 4
                assert db.execute('SELECT COUNT(*) FROM security_file_states WHERE hold=1').fetchone()[0] >= 1
            # Force a new pool, proving holds/audits survive connection teardown.
            storage.close()
            storage = PostgreSQLStorage(make_conninfo(base, options='-csearch_path='+schema))
            with storage.connect() as db:
                assert db.execute('SELECT COUNT(*) FROM security_actions').fetchone()[0] >= 4
                assert db.execute('SELECT COUNT(*) FROM security_file_states WHERE hold=1').fetchone()[0] >= 1
            print('PERSISTENT_SECURITY_PASS ' + json.dumps({'passed': 29,
                'database': 'isolated schema on existing Cloud SQL', 'files': 'existing private GCS',
                'scanner': 'real local engine', 'identity': 'in-process synthetic identities',
                'pool_recreation': 'holds and audits retained'}, sort_keys=True))
        finally:
            if storage:
                storage.close()
            for key in keys:
                files.delete(key)
                assert not files.bucket.blob(key).exists(timeout=20), 'Synthetic object cleanup failed'
            # Only this generated test schema; never drop or restore public data.
            operator.execute(sql.SQL('DROP SCHEMA {} CASCADE').format(sql.Identifier(schema)))
            assert operator.execute('SELECT 1 FROM information_schema.schemata WHERE schema_name=%s', (schema,)).fetchone() is None
            print('PERSISTENT_SECURITY_CLEANUP_PASS')


if __name__ == '__main__':
    import sys
    from pathlib import Path
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
    try:
        main()
    except Exception as error:
        # Database/provider messages can include private configuration.
        print('PERSISTENT_SECURITY_FAILED ' + type(error).__name__)
        raise SystemExit(1)
